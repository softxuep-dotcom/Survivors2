const SEPARATOR = '|||HBSEP|||';
const entries = Object.entries(EN);

function protect(value) {
  const variables = [];
  return {
    variables,
    text: value.replace(/\{[^}]+\}/g, match => {
      variables.push(match);
      return `__HBVAR${variables.length - 1}__`;
    }),
  };
}

function restore(value, variables) {
  return variables.reduce(
    (text, variable, index) => text.replaceAll(`__HBVAR${index}__`, variable),
    value.trim(),
  );
}

async function translateBatch(values, target) {
  const protectedValues = values.map(protect);
  const query = protectedValues.map(item => item.text).join(`\n${SEPARATOR}\n`);
  const url = new URL('https://translate.googleapis.com/translate_a/single');
  url.searchParams.set('client', 'gtx');
  url.searchParams.set('sl', 'en');
  url.searchParams.set('tl', target);
  url.searchParams.set('dt', 't');
  url.searchParams.set('q', query);
  let response;
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      if (response.ok) break;
    } catch (error) {
      if (attempt === 4) throw error;
    }
    await new Promise(resolve => setTimeout(resolve, attempt * 750));
  }
  if (!response?.ok) throw new Error(`Translation request failed: ${response?.status}`);
  const data = await response.json();
  const translated = data[0].map(segment => segment[0]).join('').split(SEPARATOR);
  if (translated.length !== values.length) throw new Error(`Translation split mismatch for ${target}`);
  return translated.map((value, index) => restore(value, protectedValues[index].variables));
}

async function translateLocale(target) {
  const result = {};
  const batches = [];
  for (let index = 0; index < entries.length; index += 16) {
    const batch = entries.slice(index, index + 16);
    batches.push(batch);
  }
  let cursor = 0;
  async function worker() {
    while (cursor < batches.length) {
      const batch = batches[cursor++];
      const translated = await translateBatch(batch.map(([, value]) => value), target);
      batch.forEach(([key], offset) => { result[key] = translated[offset]; });
    }
  }
  await Promise.all([worker(), worker(), worker()]);
  return result;
}

